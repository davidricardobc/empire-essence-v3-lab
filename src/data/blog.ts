export function getBlogPosts() {
  return blogPosts;
}

export function getFeaturedBlogPosts(count = 3) {
  return blogPosts.filter((post) => post.featured).slice(0, count);
}

export function getPublishedBlogPosts() {
  return blogPosts.filter((post) => post.sourceUrl);
}

export function getWholesaleBlogPosts(count = 3) {
  return blogPosts.filter((post) => post.audience === "mayorista").slice(0, count);
}

export function getBlogPostBySlug(slug: string) {
  return blogPosts.find((post) => post.slug === slug);
}

export function getRelatedBlogPosts(slug: string, count = 2) {
  const current = getBlogPostBySlug(slug);
  return blogPosts
    .filter((post) => post.slug !== slug)
    .sort((a, b) => Number(b.category === current?.category) - Number(a.category === current?.category))
    .slice(0, count);
}
